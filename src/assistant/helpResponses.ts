export function buildAssistantHelpReply(topic: string | null) {
  switch (topic) {
    case 'dispatch.create':
      return [
        '你可以直接对我说“帮我派个单，瓦黄金，要话多的小姐姐”这类话。',
        '我会先识别游戏、段位、性别偏好和软要求；如果信息不够，会继续追问你补充。',
        '整理好后我会先发确认，确认后再按当前匿名派单流程发出去。',
      ].join('\n');
    case 'order.create':
      return [
        '你可以说“给 1101 点单”或“点刚才那个陪玩”。',
        '我会先让你确认，然后弹出价格档位选择；你选完价格后，机器人再按当前匿名点单流程向陪玩发送邀请。',
        '点单前会校验陪玩是否存在，以及你的余额是否至少有 100。',
      ].join('\n');
    case 'gift.send':
      return [
        '你可以说“给她打赏 10 个棒棒糖”或“打赏 10/冰淇淋 @61111”。',
        '我会先帮你定位目标陪玩，再发确认；确认后按当前匿名打赏流程执行。',
        '如果目标不存在、礼物不存在、余额不足，或者你在给自己打赏，我会直接提示你。',
      ].join('\n');
    case 'balance.query':
      return '你可以直接说“查下我余额”或“我余额还有多少”，我会直接回复你当前余额，不需要确认。';
    case 'order.end':
      return [
        '你可以说“帮我结一下刚才那单”或“结单 #1234”。',
        '我会先定位你当前可操作的进行中订单，再发确认；确认后才真正结单。',
      ].join('\n');
    case 'invite.accept':
      return '如果你是陪玩，可以直接说“接单”“我接”。我会定位你最近待处理的邀请，确认后帮你接单。';
    case 'invite.decline':
      return '如果你不想接，可以直接说“拒单”“不接”。我会定位你最近待处理的邀请，确认后帮你拒单。';
    case 'worker.id.query':
      return '你可以直接问“我的陪玩id是多少”或“查下我的陪玩编号”，我会按你的账号直接查库返回。';
    default:
      return [
        '我现在可以帮你处理这些事：派单、点单、接单、拒单、结单、打赏、查余额、查自己的陪玩ID。',
        '常见说法例如：',
        '“帮我派个单，瓦黄金，要话多的小姐姐”',
        '“给 1101 点单”',
        '“帮我结一下刚才那单”',
        '“给她打赏 10 个棒棒糖”',
        '“查下我余额”',
        '“我的陪玩id是多少”',
      ].join('\n');
  }
}

